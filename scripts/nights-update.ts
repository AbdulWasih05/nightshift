// Regenerates docs/NIGHTS.md from the database. Never edit NIGHTS.md by hand: every number here is a query.
// Columns with no data yet (approvals, maintainer minutes) print "n/a", never an estimate.
import 'dotenv/config';
import { writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import pg from 'pg';

const db = new pg.Pool({ connectionString: process.env.DATABASE_URL });

interface NightRow {
  id: number;
  started_at: Date;
  finished_at: Date | null;
  status: string;
  trigger: string;
  repos: string[];
  prompt_version: string | null;
  notes: string | null;
  triaged: string;
  new_items: string;
  parse_fail: string;
  median_ms: number | null;
  tokens_in: string | null;
  tokens_out: string | null;
  labelled: string;
  correct: string;
  approved: string;
  edited: string;
  skipped: string;
  posted: string;
  errors: string;
}

try {
  const nights = (
    await db.query<NightRow>(`
      SELECT n.*,
        (SELECT count(*) FROM triage t WHERE t.night_id = n.id AND t.prompt_version = n.prompt_version) AS triaged,
        (SELECT count(*) FROM triage t WHERE t.night_id = n.id AND t.prompt_version = n.prompt_version
           AND NOT EXISTS (SELECT 1 FROM triage p WHERE p.item_id = t.item_id AND p.night_id < n.id)) AS new_items,
        (SELECT count(*) FROM triage t WHERE t.night_id = n.id AND t.prompt_version = n.prompt_version AND NOT t.parse_ok) AS parse_fail,
        (SELECT percentile_cont(0.5) WITHIN GROUP (ORDER BY latency_ms) FROM triage t WHERE t.night_id = n.id AND t.prompt_version = n.prompt_version) AS median_ms,
        (SELECT sum(tokens_in) FROM triage t WHERE t.night_id = n.id AND t.prompt_version = n.prompt_version) AS tokens_in,
        (SELECT sum(tokens_out) FROM triage t WHERE t.night_id = n.id AND t.prompt_version = n.prompt_version) AS tokens_out,
        (SELECT count(*) FROM triage t JOIN labels_human l ON l.item_id = t.item_id AND l.night_id = t.night_id WHERE t.night_id = n.id AND t.prompt_version = n.prompt_version) AS labelled,
        (SELECT count(*) FROM triage t JOIN labels_human l ON l.item_id = t.item_id AND l.night_id = t.night_id WHERE t.night_id = n.id AND t.prompt_version = n.prompt_version AND l.bucket = t.bucket AND t.parse_ok) AS correct,
        (SELECT count(*) FROM approvals a JOIN triage t ON t.id = a.triage_id WHERE t.night_id = n.id AND t.prompt_version = n.prompt_version AND a.action = 'approve') AS approved,
        (SELECT count(*) FROM approvals a JOIN triage t ON t.id = a.triage_id WHERE t.night_id = n.id AND t.prompt_version = n.prompt_version AND a.action = 'edit') AS edited,
        (SELECT count(*) FROM approvals a JOIN triage t ON t.id = a.triage_id WHERE t.night_id = n.id AND t.prompt_version = n.prompt_version AND a.action = 'skip') AS skipped,
        (SELECT count(*) FROM approvals a JOIN triage t ON t.id = a.triage_id WHERE t.night_id = n.id AND t.prompt_version = n.prompt_version AND a.action = 'post') AS posted,
        (SELECT count(*) FROM collect_errors e WHERE e.night_id = n.id) AS errors
      FROM nights n ORDER BY n.id`)
  ).rows;

  const buckets = (
    await db.query<{ night_id: number; bucket: string; n: string }>(
      `SELECT t.night_id, t.bucket, count(*) AS n FROM triage t JOIN nights n ON n.id = t.night_id
        WHERE t.prompt_version = n.prompt_version GROUP BY 1, 2 ORDER BY 1, 2`,
    )
  ).rows;
  const models = (
    await db.query<{ night_id: number; model_path: string; n: string }>(
      `SELECT t.night_id, t.model_path, count(*) AS n FROM triage t JOIN nights n ON n.id = t.night_id
        WHERE t.prompt_version = n.prompt_version GROUP BY 1, 2 ORDER BY 1, 2`,
    )
  ).rows;
  const perRepo = (
    await db.query<{ night_id: number; repo: string; n: string }>(
      `SELECT t.night_id, i.repo, count(*) AS n FROM triage t JOIN items i ON i.id = t.item_id JOIN nights n ON n.id = t.night_id
        WHERE t.prompt_version = n.prompt_version GROUP BY 1, 2 ORDER BY 1, 2`,
    )
  ).rows;

  const fmtDate = (d: Date) => d.toISOString().slice(0, 16).replace('T', ' ') + ' UTC';
  const dur = (a: Date, b: Date | null) => (b ? `${Math.round((b.getTime() - a.getTime()) / 60000)} min` : 'running');
  const list = <T extends { night_id: number; n: string }>(rows: T[], id: number, key: (r: T) => string) =>
    rows.filter((r) => r.night_id === id).map((r) => `${key(r)} ${r.n}`).join(', ') || 'none';
  const na = (n: string) => (Number(n) === 0 ? '0' : n);

  const out: string[] = [];
  out.push('# Nights');
  out.push('');
  out.push(`Generated by \`pnpm nights:update\` from the database at ${fmtDate(new Date())}. Do not edit by hand.`);
  out.push('');
  out.push('Accuracy is measured only on items a human labelled for that night (`labels_human`); a parse-failure fallback never counts as correct. "n/a" means no data yet, not zero.');
  out.push('');
  const header =
    '| Night | Started | Status | Duration | Triaged (first time) | Parse fails | Median latency | Tokens in/out | Labelled | Correct | Drafts approved / edited / skipped / posted | Errors |';
  const rule = '|---|---|---|---|---|---|---|---|---|---|---|---|';
  const row = (n: NightRow) => {
    const labelled = Number(n.labelled);
    return (
      `| ${n.id} | ${fmtDate(n.started_at)} | ${n.status} | ${dur(n.started_at, n.finished_at)} | ${n.triaged} (${n.new_items}) | ${n.parse_fail} | ` +
      `${n.median_ms === null ? 'n/a' : `${(Number(n.median_ms) / 1000).toFixed(1)}s`} | ${n.tokens_in ?? 0} / ${n.tokens_out ?? 0} | ` +
      `${labelled || 'n/a'} | ${labelled ? `${n.correct} (${Math.round((100 * Number(n.correct)) / labelled)}%)` : 'n/a'} | ` +
      `${na(n.approved)} / ${na(n.edited)} / ${na(n.skipped)} / ${na(n.posted)} | ${n.errors} |`
    );
  };
  const scheduled = nights.filter((n) => n.trigger === 'scheduled');
  const manual = nights.filter((n) => n.trigger === 'manual');
  out.push('## Scheduled nights (02:00 runs)');
  out.push('');
  if (scheduled.length) out.push(header, rule, ...scheduled.map(row));
  else out.push('None yet.');
  out.push('');
  out.push('## Manual runs (smoke tests, test runs; listed separately, not counted as nights)');
  out.push('');
  if (manual.length) out.push(header, rule, ...manual.map(row));
  else out.push('None.');
  out.push('');
  out.push('"Triaged (first time)": items triaged that night, and in brackets how many had never been triaged before (busy items are re-triaged when they change).');
  out.push('');
  for (const n of nights) {
    out.push(`## Night ${n.id} (${n.trigger}, prompt ${n.prompt_version ?? '?'})`);
    out.push('');
    out.push(`- Repos: ${n.repos.join(', ')}`);
    out.push(`- Triaged per repo: ${list(perRepo, n.id, (r) => r.repo)}`);
    out.push(`- Buckets: ${list(buckets, n.id, (r) => r.bucket)}`);
    out.push(`- Model path: ${list(models, n.id, (r) => r.model_path)}`);
    const hosted = Number(models.find((m) => m.night_id === n.id && m.model_path === 'hosted')?.n ?? 0);
    out.push(hosted ? `- Model calls: ${hosted} on the hosted fallback (not $0.00); the rest local` : '- Model calls: all local, $0.00');
    if (n.notes) out.push(`- Notes: ${n.notes.split('\n').join('; ')}`);
    out.push('');
  }
  const file = join(import.meta.dirname, '..', 'docs', 'NIGHTS.md');
  await writeFile(file, out.join('\n'), 'utf8');
  console.log(`wrote ${file} (${nights.length} nights)`);
} finally {
  await db.end();
}
