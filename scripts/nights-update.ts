// Regenerates docs/NIGHTS.md from the database. Never edit NIGHTS.md by hand: every number here is a query.
// Columns with no data yet (approvals, maintainer minutes) print "n/a", never an estimate.
import 'dotenv/config';
import { writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import pg from 'pg';

const db = new pg.Pool({ connectionString: process.env.DATABASE_URL });

interface NightRow {
  id: number;
  started_at: Date;
  finished_at: Date | null;
  status: string;
  trigger: string;
  repos: string[];
  prompt_version: string | null;
  notes: string | null;
  triaged: string;
  parse_fail: string;
  median_ms: number | null;
  tokens_in: string | null;
  tokens_out: string | null;
  labelled: string;
  correct: string;
  approved: string;
  edited: string;
  skipped: string;
  posted: string;
  errors: string;
}

try {
  const nights = (
    await db.query<NightRow>(`
      SELECT n.*,
        (SELECT count(*) FROM triage t WHERE t.night_id = n.id) AS triaged,
        (SELECT count(*) FROM triage t WHERE t.night_id = n.id AND NOT t.parse_ok) AS parse_fail,
        (SELECT percentile_cont(0.5) WITHIN GROUP (ORDER BY latency_ms) FROM triage t WHERE t.night_id = n.id) AS median_ms,
        (SELECT sum(tokens_in) FROM triage t WHERE t.night_id = n.id) AS tokens_in,
        (SELECT sum(tokens_out) FROM triage t WHERE t.night_id = n.id) AS tokens_out,
        (SELECT count(*) FROM triage t JOIN labels_human l ON l.item_id = t.item_id WHERE t.night_id = n.id) AS labelled,
        (SELECT count(*) FROM triage t JOIN labels_human l ON l.item_id = t.item_id WHERE t.night_id = n.id AND l.bucket = t.bucket) AS correct,
        (SELECT count(*) FROM approvals a JOIN triage t ON t.id = a.triage_id WHERE t.night_id = n.id AND a.action = 'approve') AS approved,
        (SELECT count(*) FROM approvals a JOIN triage t ON t.id = a.triage_id WHERE t.night_id = n.id AND a.action = 'edit') AS edited,
        (SELECT count(*) FROM approvals a JOIN triage t ON t.id = a.triage_id WHERE t.night_id = n.id AND a.action = 'skip') AS skipped,
        (SELECT count(*) FROM approvals a JOIN triage t ON t.id = a.triage_id WHERE t.night_id = n.id AND a.action = 'post') AS posted,
        (SELECT count(*) FROM collect_errors e WHERE e.night_id = n.id) AS errors
      FROM nights n ORDER BY n.id`)
  ).rows;

  const buckets = (
    await db.query<{ night_id: number; bucket: string; n: string }>(
      'SELECT night_id, bucket, count(*) AS n FROM triage WHERE night_id IS NOT NULL GROUP BY 1, 2 ORDER BY 1, 2',
    )
  ).rows;
  const models = (
    await db.query<{ night_id: number; model_path: string; n: string }>(
      'SELECT night_id, model_path, count(*) AS n FROM triage WHERE night_id IS NOT NULL GROUP BY 1, 2 ORDER BY 1, 2',
    )
  ).rows;
  const perRepo = (
    await db.query<{ night_id: number; repo: string; n: string }>(
      `SELECT t.night_id, i.repo, count(*) AS n FROM triage t JOIN items i ON i.id = t.item_id
        WHERE t.night_id IS NOT NULL GROUP BY 1, 2 ORDER BY 1, 2`,
    )
  ).rows;

  const fmtDate = (d: Date) => d.toISOString().slice(0, 16).replace('T', ' ') + ' UTC';
  const dur = (a: Date, b: Date | null) => (b ? `${Math.round((b.getTime() - a.getTime()) / 60000)} min` : 'running');
  const list = <T extends { night_id: number; n: string }>(rows: T[], id: number, key: (r: T) => string) =>
    rows.filter((r) => r.night_id === id).map((r) => `${key(r)} ${r.n}`).join(', ') || 'none';
  const na = (n: string) => (Number(n) === 0 ? '0' : n);

  const out: string[] = [];
  out.push('# Nights');
  out.push('');
  out.push(`Generated by \`pnpm nights:update\` from the database at ${fmtDate(new Date())}. Do not edit by hand.`);
  out.push('');
  out.push('Accuracy is measured only on items a human labelled (`labels_human`). "n/a" means no data yet, not zero.');
  out.push('');
  out.push('| Night | Started | Trigger | Status | Duration | Triaged | Parse fails | Median latency | Tokens in/out | Labelled | Correct | Drafts approved / edited / skipped / posted | Errors |');
  out.push('|---|---|---|---|---|---|---|---|---|---|---|---|---|');
  for (const n of nights) {
    const labelled = Number(n.labelled);
    out.push(
      `| ${n.id} | ${fmtDate(n.started_at)} | ${n.trigger} | ${n.status} | ${dur(n.started_at, n.finished_at)} | ${n.triaged} | ${n.parse_fail} | ` +
        `${n.median_ms === null ? 'n/a' : `${(Number(n.median_ms) / 1000).toFixed(1)}s`} | ${n.tokens_in ?? 0} / ${n.tokens_out ?? 0} | ` +
        `${labelled || 'n/a'} | ${labelled ? `${n.correct} (${Math.round((100 * Number(n.correct)) / labelled)}%)` : 'n/a'} | ` +
        `${na(n.approved)} / ${na(n.edited)} / ${na(n.skipped)} / ${na(n.posted)} | ${n.errors} |`,
    );
  }
  out.push('');
  for (const n of nights) {
    out.push(`## Night ${n.id} (${n.trigger}, prompt ${n.prompt_version ?? '?'})`);
    out.push('');
    out.push(`- Repos: ${n.repos.join(', ')}`);
    out.push(`- Triaged per repo: ${list(perRepo, n.id, (r) => r.repo)}`);
    out.push(`- Buckets: ${list(buckets, n.id, (r) => r.bucket)}`);
    out.push(`- Model path: ${list(models, n.id, (r) => r.model_path)}`);
    out.push(`- Cost: $0.00 (local models only)${models.some((m) => m.night_id === n.id && m.model_path === 'hosted') ? '; hosted calls listed above' : ''}`);
    if (n.notes) out.push(`- Notes: ${n.notes.split('\n').join('; ')}`);
    out.push('');
  }
  const file = join(import.meta.dirname, '..', 'docs', 'NIGHTS.md');
  await writeFile(file, out.join('\n'), 'utf8');
  console.log(`wrote ${file} (${nights.length} nights)`);
} finally {
  await db.end();
}
